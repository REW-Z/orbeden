using System.Text;

//生成 Core 通用类型化调用器，不生成游戏 C# 包装类
internal static class NativeMethodGenerator
{
    internal static void Generate(string outputDir)
    {
        StringBuilder code = new("// <auto-generated />\n#nullable enable\nusing System;\nusing System.Runtime.CompilerServices;\n//按值入口只接收已验证的不含托管引用类型\n#pragma warning disable CA1420\nnamespace Orbeden;\n\n");
        for (int count = 0; count <= 16; count++)
        {
            EmitType(code, count, false);
            EmitType(code, count, true);
        }
        code.AppendLine("public sealed unsafe partial class ComponentProxy");
        code.AppendLine("{");
        for (int count = 0; count <= 16; count++)
        {
            EmitBind(code, count, false);
            EmitBind(code, count, true);
        }
        code.AppendLine("}");
        string path = Path.Combine(outputDir, "NativeMethods.Generated.cs");
        string source = code.ToString();
        if (!File.Exists(path) || File.ReadAllText(path) != source)
            File.WriteAllText(path, source, new UTF8Encoding(false));
    }

    //拼接泛型参数
    private static string Generic(IEnumerable<string> types)
    {
        string joined = string.Join(", ", types);
        return joined.Length == 0 ? "" : $"<{joined}>";
    }

    //生成原生调用委托声明
    private static void EmitType(StringBuilder code, int count, bool action)
    {
        string[] args = Enumerable.Range(0, count).Select(i => $"T{i}").ToArray();
        string[] types = action ? args : [.. args, "TResult"];
        string name = (action ? "NativeAction" : "NativeMethod") + Generic(types);
        string parameters = string.Join(", ", args.Select((type, i) => $"{type} arg{i}"));
        code.AppendLine("/// <summary>直接调用原生方法的委托；失败时抛出 NativeCallException。</summary>");
        code.AppendLine($"public delegate {(action ? "void" : "TResult")} {name}({parameters});");
        code.AppendLine();
    }

    //生成签名绑定与受保护的委托调用
    private static void EmitBind(StringBuilder code, int count, bool action)
    {
        string[] args = Enumerable.Range(0, count).Select(i => $"T{i}").ToArray();
        string[] types = action ? args : [.. args, "TResult"];
        string name = (action ? "NativeAction" : "NativeMethod") + Generic(types);
        code.AppendLine("    /// <summary>按完整签名绑定原生方法；失败时输出 null，成功后通过括号直接调用。</summary>");
        code.AppendLine($"    public InteropStatus TryBind{(action ? "Action" : "Method")}{Generic(types)}(string name, out {name} method)");
        code.AppendLine("    {");
        string kinds = count == 0 ? "ReadOnlySpan<NativeValueKind>.Empty"
            : $"stackalloc NativeValueKind[] {{ {string.Join(", ", args.Select(type => $"NativeMarshaller<{type}>.Kind"))} }}";
        string result = action ? "NativeValueKind.Empty" : "NativeMarshaller<TResult>.Kind";
        string values = count == 0 ? "true" : string.Join(" && ", args.Select(type => $"!RuntimeHelpers.IsReferenceOrContainsReferences<{type}>()"));
        code.AppendLine($"        InteropStatus status = NativeMethodRuntime.Bind(handle, name, {result}, {kinds}, {values}, out NativeMethodBinding binding);");
        code.AppendLine($"        method = status == InteropStatus.Ok ? ({string.Join(", ", args.Select((_, i) => $"arg{i}"))}) =>");
        code.AppendLine("        {");
        if (count != 0)
        {
            code.AppendLine($"            if ({values})");
            code.AppendLine("            {");
        }
        EmitValueCall(code, args, action, count == 0 ? "            " : "                ");
        if (count != 0)
        {
            code.AppendLine("            }");
            code.AppendLine("            else");
            code.AppendLine("            {");
            EmitMarshalledCall(code, args, action);
            code.AppendLine("            }");
        }
        code.AppendLine("        } : null!;");
        code.AppendLine("        return status;");
        code.AppendLine("    }");
        code.AppendLine();
    }

    //直接传递具体值类型参数
    private static void EmitValueCall(StringBuilder code, string[] args, bool action, string indent)
    {
        code.AppendLine(indent + "NativeCallFrame.ThrowIfFailed(binding.TryEnter(out NativeCallFrame call));");
        code.AppendLine(indent + "try");
        code.AppendLine(indent + "{");
        string signature = string.Join(", ", new[] { "void*" }.Concat(args).Concat(action ? [] : new[] { "void*" }).Append("InteropStatus"));
        string inputs = string.Join(", ", new[] { "call.Instance" }.Concat(args.Select((_, i) => $"arg{i}")));
        string call = $"((delegate* unmanaged[Cdecl]<{signature}>)call.Entry)";
        if (action)
        {
            code.AppendLine(indent + $"    NativeCallFrame.ThrowIfFailed({call}({inputs}));");
        }
        else
        {
            code.AppendLine(indent + "    if (!RuntimeHelpers.IsReferenceOrContainsReferences<TResult>())");
            code.AppendLine(indent + "    {");
            code.AppendLine(indent + "        TResult result = default!;");
            code.AppendLine(indent + $"        NativeCallFrame.ThrowIfFailed({call}({inputs}, Unsafe.AsPointer(ref result)));");
            code.AppendLine(indent + "        return result;");
            code.AppendLine(indent + "    }");
            code.AppendLine(indent + "    NativeUtf8 output = default;");
            code.AppendLine(indent + $"    NativeCallFrame.ThrowIfFailed({call}({inputs}, &output));");
            code.AppendLine(indent + "    return NativeMarshaller<TResult>.Read(&output);");
        }
        code.AppendLine(indent + "}");
        code.AppendLine(indent + "finally { call.Dispose(); }");
    }

    //封送包含托管引用的参数签名
    private static void EmitMarshalledCall(StringBuilder code, string[] args, bool action)
    {
        code.AppendLine("            NativeCallFrame.ThrowIfFailed(binding.TryEnter(out NativeCallFrame call));");
        code.AppendLine("            NativeMarshallingScope scope = new();");
        code.AppendLine("            try");
        code.AppendLine("            {");
        for (int i = 0; i < args.Length; i++)
        {
            code.AppendLine($"                byte* input{i} = stackalloc byte[NativeMarshaller<T{i}>.Size];");
            code.AppendLine($"                NativeMarshaller<T{i}>.Write(input{i}, arg{i}, ref scope);");
        }
        if (!action) code.AppendLine("                byte* output = stackalloc byte[NativeMarshaller<TResult>.Size];");
        string signature = string.Join(", ", new[]{ "void*" }.Concat(args.Select(_ => "void*")).Concat(action ? [] : new[]{ "void*" }).Append("InteropStatus"));
        string inputs = string.Join(", ", new[]{ "call.Instance" }.Concat(args.Select((_, i) => $"input{i}")).Concat(action ? [] : new[]{ "output" }));
        code.AppendLine($"                NativeCallFrame.ThrowIfFailed(((delegate* unmanaged[Cdecl]<{signature}>)call.Entry)({inputs}));");
        if (!action) code.AppendLine("                return NativeMarshaller<TResult>.Read(output);");
        code.AppendLine("            }");
        code.AppendLine("            finally { scope.Dispose(); call.Dispose(); }");
    }
}
